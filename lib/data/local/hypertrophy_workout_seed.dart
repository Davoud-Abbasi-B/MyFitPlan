  String id,
  String name,
  String reps,
  String rir,
  String rest, {
  int sets = 3,
  required List<String> muscles,
  List<String> secondary = const [],
  String? alternative,
  String? image,
}) =>
    Exercise(
      id: id,
      name: name,
      type: ExerciseType.strength,
      sets: sets,
      reps: reps,
      notes: 'Use controlled technique and stop at the prescribed RIR.',
      targetRirText: rir,
      restText: rest,
      instructionText:
          'Use controlled technique and stop at the prescribed RIR.',
      targetMuscles: muscles,
      secondaryMuscles: secondary,
      alternativeText: alternative,
      imageAssetPath: image,
    );
